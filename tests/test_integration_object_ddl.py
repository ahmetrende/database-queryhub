"""pg_ddl against a real PostgreSQL: the script of a table must build the same
table again (Devart B5).

Run with QH_RUN_INTEGRATION=1 and QH_DDL_PG_DSN pointing at a THROWAWAY
server. The test creates the schemas qh_ddl_src and qh_ddl_dst and drops
them at the end.
"""
import os

import psycopg
import pytest

from queryhub import pg_ddl

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not (os.environ.get("QH_RUN_INTEGRATION") and os.environ.get("QH_DDL_PG_DSN")),
                       reason="set QH_RUN_INTEGRATION=1 and QH_DDL_PG_DSN (a throwaway server) to run"),
]

SETUP = """
DROP SCHEMA IF EXISTS qh_ddl_src CASCADE;
DROP SCHEMA IF EXISTS qh_ddl_dst CASCADE;
CREATE SCHEMA qh_ddl_src;
CREATE SCHEMA qh_ddl_dst;
SET search_path = qh_ddl_src;
CREATE TABLE users (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, email text NOT NULL UNIQUE);
CREATE TABLE "Order Lines" (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id int NOT NULL REFERENCES users (id),
  total numeric(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  note varchar(40),
  created_at timestamptz NOT NULL DEFAULT now(),
  doubled numeric GENERATED ALWAYS AS (total * 2) STORED,
  CONSTRAINT "Order Lines_pkey" PRIMARY KEY (id)
);
CREATE INDEX lines_by_user ON "Order Lines" (user_id, created_at DESC);
CREATE TABLE events (id int NOT NULL, at date NOT NULL) PARTITION BY RANGE (at);
CREATE VIEW big_lines AS SELECT id, total FROM "Order Lines" WHERE total > 100;
CREATE MATERIALIZED VIEW line_count AS SELECT count(*) AS n FROM "Order Lines";
CREATE FUNCTION twice(x int) RETURNS int LANGUAGE sql AS 'SELECT x * 2';
CREATE FUNCTION twice(x numeric) RETURNS numeric LANGUAGE sql AS 'SELECT x * 2';
CREATE PROCEDURE touch() LANGUAGE sql AS 'SELECT 1';
"""


@pytest.fixture(scope="module")
def cur():
    with psycopg.connect(os.environ["QH_DDL_PG_DSN"], autocommit=True) as cn, cn.cursor() as c:
        c.execute(SETUP)
        c.execute("SET search_path = qh_ddl_src")
        yield c
        c.execute("DROP SCHEMA IF EXISTS qh_ddl_src CASCADE; DROP SCHEMA IF EXISTS qh_ddl_dst CASCADE")


def _columns(c, schema, table):
    c.execute("SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attidentity, a.attgenerated, "
              "pg_get_expr(d.adbin, d.adrelid) FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid "
              "AND d.adnum = a.attnum WHERE a.attrelid = %s::regclass AND a.attnum > 0 AND NOT a.attisdropped "
              "ORDER BY a.attnum", (f'{schema}."{table}"',))
    return c.fetchall()


def _constraints(c, schema, table):
    c.execute("SELECT conname, contype, pg_get_constraintdef(oid, true) FROM pg_constraint "
              "WHERE conrelid = %s::regclass ORDER BY conname", (f'{schema}."{table}"',))
    return [(n, t, d.replace(f"{schema}.", "")) for n, t, d in c.fetchall()]


def test_a_table_script_builds_the_same_table(cur):
    kind, script, built = pg_ddl.object_ddl(cur, "qh_ddl_src", "Order Lines")
    assert (kind, built) == ("table", True)
    assert script.startswith('CREATE TABLE qh_ddl_src."Order Lines" (')
    assert 'CREATE INDEX lines_by_user ON qh_ddl_src."Order Lines" USING btree (user_id, created_at DESC);' in script
    _kind, users, _b = pg_ddl.object_ddl(cur, "qh_ddl_src", "users")
    # Build both in the empty schema: users first, for the foreign key.
    for s in (users, script):
        cur.execute(s.replace("qh_ddl_src.", "qh_ddl_dst."))
    assert _columns(cur, "qh_ddl_dst", "Order Lines") == _columns(cur, "qh_ddl_src", "Order Lines")
    assert _constraints(cur, "qh_ddl_dst", "Order Lines") == _constraints(cur, "qh_ddl_src", "Order Lines")
    cur.execute("SELECT indexdef FROM pg_indexes WHERE schemaname = 'qh_ddl_dst' AND indexname = 'lines_by_user'")
    assert cur.fetchone() is not None


def test_a_partitioned_table_keeps_its_key(cur):
    _k, script, _b = pg_ddl.object_ddl(cur, None, "events")
    assert script.endswith(") PARTITION BY RANGE (at);")


def test_views_functions_and_procedures_come_from_the_server(cur):
    kind, script, built = pg_ddl.object_ddl(cur, "qh_ddl_src", "big_lines")
    assert (kind, built) == ("view", False)
    assert script.startswith("CREATE OR REPLACE VIEW qh_ddl_src.big_lines AS\nSELECT id,")
    assert script.endswith(";")
    kind, script, _b = pg_ddl.object_ddl(cur, "qh_ddl_src", "line_count")
    assert kind == "materialized view" and script.startswith("CREATE MATERIALIZED VIEW qh_ddl_src.line_count AS")
    kind, script, _b = pg_ddl.object_ddl(cur, None, "twice")
    assert kind == "function"
    assert script.count("CREATE OR REPLACE FUNCTION qh_ddl_src.twice") == 2, "both overloads"
    assert script.rstrip().endswith(";")
    kind, script, _b = pg_ddl.object_ddl(cur, "qh_ddl_src", "touch")
    assert kind == "procedure" and "CREATE OR REPLACE PROCEDURE qh_ddl_src.touch()" in script


def test_a_missing_object_is_none(cur):
    assert pg_ddl.object_ddl(cur, "qh_ddl_src", "nothing") is None
    assert pg_ddl.object_ddl(cur, "no_schema", "users") is None
    assert pg_ddl.object_ddl(cur, None, "Users") is None, "a quoted name keeps its case"
